-- Categories. `kind` drives everything the app reads as income, fixed,
-- variable or savings. Names stay in the clear: queries order and group by them.
create table public.category (
  id bigint generated by default as identity primary key,
  category text not null,
  kind text not null default 'variable'
    check (kind in ('income', 'fixed', 'variable', 'savings')),
  user_id uuid not null references auth.users (id) on delete cascade,
  -- The target of the same-owner keys below.
  constraint category_id_user_key unique (id, user_id)
);

-- Merkelapper (trips, projects). name, budget and places are ciphertext.
create table public.tag (
  id bigint generated always as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null,
  start_date date,
  end_date date,
  budget text,
  places text,
  created_at timestamptz not null default now(),
  constraint tag_dates_check check (
    (start_date is null) = (end_date is null) and end_date >= start_date
  ),
  constraint tag_id_user_key unique (id, user_id)
);

create index tag_user_idx on public.tag (user_id);

-- Fixed-expense templates. item and price are ciphertext.
create table public.recurring_expense (
  id bigint generated always as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  item text not null,
  price text not null,
  category_id bigint not null,
  day_of_month smallint not null check (day_of_month between 1 and 31),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint recurring_expense_id_user_key unique (id, user_id),
  constraint recurring_expense_category_same_owner
    foreign key (category_id, user_id) references public.category (id, user_id)
);

create index recurring_expense_user_idx on public.recurring_expense (user_id);

-- Transactions. item and price are ciphertext; price is whole kroner, unsigned
-- (the category's kind carries the direction).
create table public.expense (
  id bigint generated by default as identity,
  item text not null,
  price text not null,
  category_id integer not null,
  user_id uuid,
  date date,
  recurring_id bigint,
  tag_id bigint,
  constraint expenses_pkey primary key (id),
  -- Every reference includes user_id, so it can only name a row of the same
  -- owner (0013). The column lists keep user_id when the target is deleted.
  constraint expense_category_same_owner
    foreign key (category_id, user_id) references public.category (id, user_id),
  constraint expense_tag_same_owner
    foreign key (tag_id, user_id) references public.tag (id, user_id)
    on delete set null (tag_id),
  constraint expense_recurring_same_owner
    foreign key (recurring_id, user_id) references public.recurring_expense (id, user_id)
    on delete set null (recurring_id)
);

create index idx_expense_date on public.expense (date);
create index expense_recurring_idx on public.expense (recurring_id);
create index expense_tag_idx on public.expense (tag_id);

-- One budget per category and month. budget is ciphertext.
create table public.budget (
  id bigint generated by default as identity primary key,
  category_id bigint not null,
  budget text not null,
  year bigint not null,
  month integer not null,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  constraint budget_category_same_owner
    foreign key (category_id, user_id) references public.category (id, user_id)
);

create unique index budget_user_cat_period_idx
  on public.budget (user_id, category_id, year, month);

-- Observed savings balances. amount is ciphertext; category stays readable
-- because it is part of the unique key (ciphertext differs on every write).
create table public.savings_snapshot (
  id bigint generated always as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  category text not null check (length(trim(category)) > 0),
  date date not null,
  amount text not null,
  created_at timestamptz not null default now(),
  unique (user_id, category, date)
);

create index savings_snapshot_user_date_idx
  on public.savings_snapshot (user_id, date);

-- Row-level security: every table is its owner's alone, on read and on write.
alter table public.category enable row level security;
alter table public.tag enable row level security;
alter table public.recurring_expense enable row level security;
alter table public.expense enable row level security;
alter table public.budget enable row level security;
alter table public.savings_snapshot enable row level security;

create policy category_owner on public.category
  for all using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy tag_owner on public.tag
  for all using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy recurring_expense_owner on public.recurring_expense
  for all using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy expense_owner on public.expense
  for all using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy budget_owner on public.budget
  for all using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "savings_snapshot is per user" on public.savings_snapshot
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- A new account starts with categories, or no form in the app can be saved.
-- security definer: the trigger runs before the user has a session, so
-- category_owner would reject the insert.
create or replace function public.seed_default_categories()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.category (category, kind, user_id)
  values
    ('Lønn',       'income',   new.id),
    ('Bolig',      'fixed',    new.id),
    ('Strøm',      'fixed',    new.id),
    ('Abonnement', 'fixed',    new.id),
    ('Mat',        'variable', new.id),
    ('Transport',  'variable', new.id),
    ('Klær',       'variable', new.id),
    ('Fritid',     'variable', new.id),
    ('Sparing',    'savings',  new.id);
  return new;
end;
$$;

create trigger seed_default_categories_on_signup
  after insert on auth.users
  for each row execute function public.seed_default_categories();
